// SHUFFLE FUNCTION
function shuffleArray(array) {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function createRow(title, index) {
  const rowId = `row-${index}`;

  const shows = shuffleArray(theatre).slice(0, 12);

  return `
    <div class="row">

    <div class="category_title">
      <h3>${title}</h3>
    </div>

      <div class="carousel-wrapper">
        <div id="${rowId}" class="carousel">
          ${shows.map(show => `
            
            <a class="card" href="${show.link}" target="_blank" rel="noopener noreferrer">
              <img src="${show.img}" alt="${show.title}">
            </a>

          `).join('')}
        </div>
      </div>
    </div>
  `
}

// SCROLL FUNCTION
function scrollRow(rowId, amount) {
  const row = document.getElementById(rowId);
  row.scrollBy({ left: amount, behavior: 'smooth' });
}

// RENDER ALL ROWS
function renderRows() {
  container.innerHTML = categories
    .map((cat, i) => createRow(cat, i))
    .join('');
}

